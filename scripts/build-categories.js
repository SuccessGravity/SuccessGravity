#!/usr/bin/env node
// Category pages from data (run after build-tools-json.js).
// - Every hand-written /category/<hub>/ page gets a full, static "every tool we track" list
//   between <!-- SG-HUBLIST:START --> and <!-- SG-HUBLIST:END --> (inserted before the closing CTA).
// - Hubs marked "new" in data/category-hubs.json get a whole generated page.
// - /category/ and the homepage "Browse by Category" grid get cards for new hubs and live counts.
// - New hub URLs are added to sitemap.xml.
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const write = (p, s) => { fs.mkdirSync(path.dirname(path.join(root, p)), { recursive: true }); fs.writeFileSync(path.join(root, p), s); };
const tools = JSON.parse(read('data/tools.json'));
const hubs = JSON.parse(read('data/category-hubs.json')).hubs;
let verified = {};
try { verified = JSON.parse(read('data/price-changes.json')).verified || {}; } catch (e) {}

const esc = (s) => String(s == null ? '' : s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const shortDate = (iso) => {
  const d = new Date(iso + 'T12:00:00Z');
  return isNaN(d) ? iso : d.toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric', timeZone: 'UTC' });
};
const host = (u) => { try { return new URL(u).hostname; } catch (e) { return ''; } };
const today = new Date().toISOString().slice(0, 10);
const monthYear = new Date().toLocaleDateString('en-US', { month: 'long', year: 'numeric', timeZone: 'UTC' });

const keyToHub = {};
Object.entries(hubs).forEach(([slug, h]) => h.keys.forEach((k) => { keyToHub[k] = slug; }));
const unmapped = [...new Set(tools.tools.map((t) => t.c))].filter((k) => !keyToHub[k]);
if (unmapped.length) console.warn('categories without a hub (add them to data/category-hubs.json): ' + unmapped.join(', '));

function hubTools(slug) {
  const keys = new Set(hubs[slug].keys);
  return tools.tools.filter((t) => keys.has(t.c)).sort((a, b) =>
    (b.rv ? 1 : 0) - (a.rv ? 1 : 0) ||
    (b.r != null ? 1 : 0) - (a.r != null ? 1 : 0) ||
    (b.r || 0) - (a.r || 0) ||
    ((verified[b.id] || b.vd) ? 1 : 0) - ((verified[a.id] || a.vd) ? 1 : 0) ||
    (b.pop || 0) - (a.pop || 0) ||
    a.n.localeCompare(b.n));
}

function toolCard(t) {
  const v = verified[t.id] || (t.vd ? { date: t.vd, source: t.vs } : null);
  const h = host(t.l);
  const logo = '<img src="https://www.google.com/s2/favicons?domain=' + encodeURIComponent(h) + '&amp;sz=64" alt="" width="28" height="28" loading="lazy" class="sgc-logo">';
  const name = t.rv ? '<a href="' + esc(t.rv) + '" class="sgc-name">' + esc(t.n) + '</a>' : '<span class="sgc-name">' + esc(t.n) + '</span>';
  const badge = t.rv ? '<span class="sgc-badge sgc-rev">&#11088; Reviewed ' + esc(t.r) + '/5</span>'
    : t.r != null ? '<span class="sgc-badge">&#9733; ' + esc(t.r) + '/5</span>'
    : '<span class="sgc-badge sgc-new">New listing</span>';
  const price = '<p class="sgc-price">' + esc(t.p || 'See official site') +
    (v ? ' <a href="' + esc(v.source) + '" target="_blank" rel="noopener" class="sgc-ver" title="Price checked on the vendor&#39;s own page">&#10003; checked ' + esc(shortDate(v.date)) + '</a>' : '') + '</p>';
  return '        <article class="sgc-tool">\n' +
    '          <div class="sgc-top">' + logo + '<div class="sgc-head">' + name + badge + '</div></div>\n' +
    '          ' + price + '\n' +
    '          <p class="sgc-desc">' + esc(t.b) + '</p>\n' +
    '          <div class="sgc-actions"><a href="' + esc(t.l) + '" target="_blank" rel="sponsored noopener" class="affiliate-link sg-cta sgc-visit" data-tool="' + esc(t.id) + '">Visit site</a>' +
    '<button type="button" class="sg-btn-ghost sg-btn-sm sg-stack-btn" data-stack-id="' + esc(t.id) + '">&#65291; Add to My Stack</button></div>\n' +
    '        </article>';
}

function listBlock(slug) {
  const h = hubs[slug];
  const list = hubTools(slug);
  const nVer = list.filter((t) => verified[t.id] || t.vd).length;
  return '<!-- SG-HUBLIST:START (generated by scripts/build-categories.js — edit data, not this block) -->\n' +
    '    <section class="mt-14 sgc-list" id="all-tools">\n' +
    '      <div class="flex flex-wrap items-end justify-between gap-3 mb-5">\n' +
    '        <div>\n' +
    '          <h2 class="text-2xl font-bold text-gray-900">Every ' + esc(h.name) + ' tool we track (' + list.length + ')</h2>\n' +
    '          <p class="text-sm text-gray-500 mt-1">Prices are the cheapest paid plan. &#10003; means we checked it on the vendor&rsquo;s own pricing page (' + nVer + ' of ' + list.length + '). Newly listed tools aren&rsquo;t rated until we review them.</p>\n' +
    '        </div>\n' +
    '        <a href="/stack/" class="sg-btn-primary sg-btn-sm">&#129520; Total up your stack &rarr;</a>\n' +
    '      </div>\n' +
    '      <div class="sgc-grid">\n' + list.map(toolCard).join('\n') + '\n      </div>\n' +
    '    </section>\n' +
    '<!-- SG-HUBLIST:END -->';
}

function putBlock(html, block, beforeRe) {
  const re = /<!-- SG-HUBLIST:START[\s\S]*?<!-- SG-HUBLIST:END -->/;
  if (re.test(html)) return html.replace(re, () => block);
  const m = html.match(beforeRe);
  if (!m) return null;
  return html.slice(0, m.index) + block + '\n\n' + html.slice(m.index);
}

// ---- 1. Existing hand-written hub pages ----
const ctaRe = /    <section class="mt-14 rounded-2xl sg-hero text-white[^>]*>\s*<h2[^>]*>Not sure which tool fits\?/;
let changed = 0;
Object.entries(hubs).forEach(([slug, h]) => {
  if (h.new) return;
  const rel = 'category/' + slug + '/index.html';
  if (!fs.existsSync(path.join(root, rel))) { console.warn('missing hub page ' + rel); return; }
  const html = read(rel);
  let out = putBlock(html, listBlock(slug), ctaRe);
  if (!out) out = putBlock(html, listBlock(slug), /\n  <\/main>/);
  if (!out) { console.warn('no insertion point in ' + rel); return; }
  if (out !== html) { write(rel, out); changed++; }
});

// ---- 2. Generated pages for new hubs (shell copied from an existing hub) ----
const shellSrc = read('category/crm/index.html');
const headEnd = shellSrc.indexOf('<header');
const footStart = shellSrc.indexOf('  <footer');
Object.entries(hubs).forEach(([slug, h]) => {
  if (!h.new) return;
  const rel = 'category/' + slug + '/index.html';
  const list = hubTools(slug);
  const url = 'https://successgravity.com/category/' + slug + '/';
  const title = esc(h.name) + ' Tools — Prices &amp; Free Plans (' + new Date().getUTCFullYear() + ') | Success Gravity';
  const desc = esc(h.blurb);
  let head = shellSrc.slice(0, headEnd)
    .replace(/<title>[\s\S]*?<\/title>/, '<title>' + title + '</title>')
    .replace(/(<meta name="description" content=")[^"]*/, '$1' + desc)
    .replace(/(<link rel="canonical" href=")[^"]*/, '$1' + url)
    .replace(/(<meta property="og:title" content=")[^"]*/, '$1' + title)
    .replace(/(<meta property="og:description" content=")[^"]*/, '$1' + desc)
    .replace(/(<meta property="og:url" content=")[^"]*/, '$1' + url)
    .replace(/<script type="application\/ld\+json">[\s\S]*?<\/script>\s*/g, '')
    .replace(/\s*<meta name="robots"[^>]*>/g, '');
  const ld = { '@context': 'https://schema.org', '@type': 'CollectionPage', name: h.name + ' Tools', url, description: h.blurb,
    publisher: { '@type': 'Organization', name: 'Success Gravity', url: 'https://successgravity.com/' },
    mainEntity: { '@type': 'ItemList', numberOfItems: list.length, itemListElement: list.slice(0, 30).map((t, i) => ({ '@type': 'ListItem', position: i + 1, name: t.n, url: t.rv ? 'https://successgravity.com' + t.rv : t.l })) } };
  head = head.replace('</head>', '  <script type="application/ld+json">' + JSON.stringify(ld) + '</script>\n</head>');
  const body =
    '<header class="sg-hero text-white">\n' +
    '    <div class="container mx-auto px-4 py-14 md:py-20">\n' +
    '      <p class="text-indigo-200 text-sm font-semibold mb-2"><a href="/category/" class="hover:text-white">Categories</a> / ' + esc(h.name) + '</p>\n' +
    '      <h1 class="text-3xl md:text-5xl font-extrabold leading-tight mb-4">' + h.emoji + ' <span class="sg-hero-accent">' + esc(h.name) + '</span> Tools</h1>\n' +
    '      <p class="text-indigo-100 max-w-2xl text-lg">' + esc(h.blurb) + '</p>\n' +
    '      <p class="text-indigo-300 text-xs mt-4">Last updated: ' + monthYear + ' · ' + list.length + ' tools · Prices checked at the source</p>\n' +
    '    </div>\n' +
    '  </header>\n\n' +
    '  <main class="container mx-auto px-4 py-12 max-w-6xl">\n' +
    '    <section class="sg-prose max-w-3xl">\n' +
    (h.intro || []).map((p) => '      <p>' + esc(p) + '</p>\n').join('') +
    ((h.lookFor || []).length ? '      <h3>What to look for</h3>\n      <ul>\n' + h.lookFor.map((x) => '        <li>' + esc(x) + '</li>\n').join('') + '      </ul>\n' : '') +
    '    </section>\n\n' +
    '    ' + listBlock(slug) + '\n\n' +
    '    <section class="mt-14" data-sg-newsletter="card"></section>\n' +
    '  </main>\n\n';
  const page = head + body + shellSrc.slice(footStart);
  const prev = fs.existsSync(path.join(root, rel)) ? read(rel) : '';
  if (page !== prev) { write(rel, page); changed++; }
});

// ---- 3. Cards and counts on /category/ and the homepage grid ----
function setCounts(html) {
  return html.replace(/(<a href="\/category\/([a-z0-9-]+)\/"[\s\S]*?<span class="sg-chip sg-acc-indigo">)(\d+)( tools<\/span>)/g, (m, a, slug, n, b) =>
    hubs[slug] ? a + hubTools(slug).length + b : m);
}
function putNewCards(html, cards, beforeRe) {
  const re = /<!-- SG-NEWHUBS:START -->[\s\S]*?<!-- SG-NEWHUBS:END -->/;
  const block = '<!-- SG-NEWHUBS:START -->\n' + cards + '\n      <!-- SG-NEWHUBS:END -->';
  if (re.test(html)) return html.replace(re, () => block);
  const m = html.match(beforeRe);
  return m ? html.slice(0, m.index) + '      ' + block + '\n' + html.slice(m.index) : html;
}
const newHubs = Object.entries(hubs).filter(([, h]) => h.new);
{
  const rel = 'category/index.html';
  const html = read(rel);
  const cards = newHubs.map(([slug, h]) => {
    const list = hubTools(slug);
    return '      <a href="/category/' + slug + '/" class="sg-card2 sg-reveal block hover:no-underline">\n' +
      '        <div class="text-3xl mb-2">' + h.emoji + '</div>\n' +
      '        <h2 class="font-bold text-gray-900 text-lg leading-snug mb-1">' + esc(h.name) + '</h2>\n' +
      '        <p class="text-sm text-gray-600 leading-relaxed mb-3">' + esc(h.blurb) + '</p>\n' +
      '        <p class="text-xs text-gray-500"><span class="sg-chip sg-acc-indigo">' + list.length + ' tools</span> <span class="sg-chip sg-acc-green ml-1">New</span></p>\n' +
      '      </a>';
  }).join('\n');
  const out = setCounts(putNewCards(html, cards, /    <\/div>\n  <\/main>/));
  if (out !== html) { write(rel, out); changed++; }
}
{
  const rel = 'index.html';
  const html = read(rel);
  const cards = newHubs.map(([slug, h]) =>
    '        <a href="/category/' + slug + '/" class="sg-card2 sg-reveal block hover:no-underline text-center py-5"><span class="text-2xl block mb-1">' + h.emoji + '</span><span class="font-semibold text-gray-900 text-sm">' + esc(h.name) + '</span></a>').join('\n');
  const out = putNewCards(html, cards, /      <\/div>\n      <p class="text-center mt-6"><a href="\/category\/"/);
  if (out !== html) { write(rel, out); changed++; }
}

// ---- 4. Sitemap ----
{
  let sm = read('sitemap.xml');
  let added = 0;
  newHubs.forEach(([slug]) => {
    const u = 'https://successgravity.com/category/' + slug + '/';
    if (sm.indexOf('<loc>' + u + '</loc>') === -1) {
      sm = sm.replace('</urlset>', '  <url><loc>' + u + '</loc><lastmod>' + today + '</lastmod><changefreq>weekly</changefreq><priority>0.7</priority></url>\n</urlset>');
      added++;
    }
  });
  if (added) { write('sitemap.xml', sm); changed++; }
}

console.log('categories: ' + Object.keys(hubs).length + ' hubs (' + newHubs.length + ' generated), ' + changed + ' file(s) updated');
